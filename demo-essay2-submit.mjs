// 手写作文《创造转化文化 兼收并蓄美德》→ 真实批改
const B = 'http://localhost:3001';

const essay = `当代，传承中华优秀传统文化一直是社交媒体上常见的热点。传承这些文化的方式也越来越多，比如有博主慢火慢煨、展示古法的短视频，也有逼真的建模复刻式数字化，还有传播者亲口的各种叫卖声、方言录音，以这些方式储存下来在网络上传播。我认为这些传承方式都是可行的，且对传承有用。原汁原味的录音自然可行，但在如今数字化、信息化的时代，建模复刻同样可以是一种好的传承方式。

原汁原味的传承，最大的好处就是可以将传统文化完整地复制下来，使现代的我们更好地感受前人的智慧。但只靠这样的方式学习传统文化，也会产生对先前文化的错误理解。并且，原汁原味的传承会有不可避免的风险：文化或许能保留在文化馆、博物馆之中，却很难传进人的心中。如今的古法织造、昆曲也都面临着这样的问题，没有年轻人愿意花时间学习。可见原汁原味的方式并非万能，且具有一定的局限性。

而文化的创造性转化、创新性发展，则有助于文化从传承走向传播、走向流行，这样才能与时俱进，不淹没在时代的浪潮之下。

对于文化的创造性转化，最核心的立足点，是在不损害文化核心内容的情况下，对其呈现形式、传播方向进行转变，以适应时代的特点。这样的转变并不代表对文化的背叛。相反，它虽不能完全保留传统文化的全部细节，却可以将文化推向大众，让传统文化焕发活力，拥有蓬勃的生命力，进而带动人们学习传统文化，更好地传承下去。从文旅的繁华，到侗族大歌交融的精彩节目，再到打铁花在网络平台上的快速传播，这些都不再只是从欣赏角度的储存。人们能感受到文化的美好，进而自发地去了解，更能让文化活在人们心中，代代相传。

文化本身不是一个一成不变的物品，而是由一部分人的行为、爱好或习惯逐渐形成的。与文化最好的相处方式，是被创造出来的——文化就是那个时代人们共同的特点，本身具有时代特征与一定的时效性。当下一代人进入社会、上一代人离开社会，这种更替本身就会带来文化的产生与消失。因此传承文化，就不能只让它在极小的人群中保留，而应当以留住这一代人文化的方式，融入他们的文化，这样才能使文化做到真正的代代相传。

文化传承的意义不仅在于记录历史，更是将前人智慧的结晶、一代代文化融入后人的思想之中，使得他们变得更好，保证社会道德与文化上的稳定。唯有传承，才能让传统文化为人们更好地服务。

让我们一起来传承、发展我们的文化吧！在优秀文化的滋养下成长进步，吸纳、学习、借鉴这些有益的文化。`;

const topic = '关于中华优秀传统文化的传承，有人认为应原汁原味地保留，也有人认为应进行创造性转化、创新性发展。请写一篇文章，谈谈你的思考。';

const r = await fetch(`${B}/analyze`, {
  method: 'POST',
  headers: { 'Content-Type': 'application/json' },
  body: JSON.stringify({ text: essay, topic })
});
const d = await r.json();
console.log('提交:', r.status, d.taskId || d.error);
if (!d.taskId) process.exit(1);

for (let i = 0; i < 100; i++) {
  await new Promise(s => setTimeout(s, 5000));
  const t = await (await fetch(`${B}/task/${d.taskId}`)).json();
  if (i % 6 === 0) console.log(`  [${i * 5}s] ${t.status} ${t.progress?.message || ''}`);
  if (t.status === 'done') {
    const fs = await import('fs');
    fs.writeFileSync('demo-grading-result2.json', JSON.stringify(t.result, null, 2), 'utf-8');
    console.log('✅ 完成! 总分:', t.result?.totalScore, '| 等级:', t.result?.grade);
    process.exit(0);
  }
  if (t.status === 'failed') { console.log('❌ 失败:', t.error); process.exit(1); }
}
console.log('超时');
