export function buildMessages({ subject, imageBase64 }) {
  const subj = subject || '物理';
  return [
    {
      role: 'user',
      content: [
        { type: 'text', text: PROMPT.replace(/\{subject\}/g, subj) + `\n\n当前学科：${subj}` },
        { type: 'image_url', image_url: { url: imageBase64, detail: 'auto' } }
      ]
    }
  ];
}
